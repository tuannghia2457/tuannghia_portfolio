import { test, expect } from '@playwright/test'
test('Recognition rows stay compact, show only name and result, and link to their project', async ({ page }) => {
  await page.goto('/projects')
  await page.locator('summary').getByText('Awards & certificates', { exact: true }).click()
  const panel = page.locator('.recognition-panel'), cards = panel.locator('.recognition-item')
  await expect(cards).toHaveCount(6)
  await expect(panel).not.toContainText('Dean')
  await expect(panel.getByRole('heading', { name: 'Bach Khoa Innovation' })).toBeVisible()
  await expect(cards.first()).toHaveText(/Bach Khoa Innovation 2026\s*First Runner-Up/)
  expect(await cards.first().evaluate(el => el.getBoundingClientRect().height)).toBeLessThan(110)
  expect(await panel.evaluate(el => parseFloat(getComputedStyle(el).paddingLeft))).toBeGreaterThanOrEqual(14)
  await cards.first().click()
  await expect(page).toHaveURL(/\/projects\/aquaguard$/)
  await page.goto('/projects'); await page.setViewportSize({ width: 320, height: 800 })
  await page.locator('summary').getByText('Awards & certificates', { exact: true }).click()
  await expect(cards.last()).toHaveAttribute('href', '/projects/virtualdouble-ant')
  await expect(cards.last()).toContainText('Finalist')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})
