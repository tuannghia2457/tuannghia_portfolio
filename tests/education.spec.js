import { test, expect } from '@playwright/test'
test('Academic achievements live under Education while Projects show only external recognition', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Education' }).click()
  await expect(page).toHaveURL(/\/education$/)
  await expect(page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Education' })).toHaveAttribute('aria-current', 'page')
  const education = page.locator('#education')
  await expect(education.getByRole('heading', { level: 1, name: 'Education.' })).toBeVisible()
  // Chronological timeline: PTNK, then UTS with HCMUT shown as its transnational partner.
  await expect(education.locator('.education-milestone')).toHaveCount(2)
  await expect(education.locator('.education-milestone h3')).toHaveText([/High School for the Gifted/, 'University of Technology Sydney'])
  await expect(education.locator('.school-more[open]')).toHaveCount(0)
  const uts = education.locator('.education-milestone').last()
  await expect(uts.locator('.milestone-badge')).toHaveText('Current')
  await expect(uts.locator('.milestone-expected')).toHaveText('Expected May 2028')
  await expect(uts.locator('.milestone-partner a')).toHaveAttribute('href', 'https://hcmut.edu.vn')
  await expect(uts.locator('.milestone-highlights li')).toHaveText(['GPA 6.9 / 7.0', 'Dean’s List 2026'])
  await expect(uts.getByRole('heading', { name: 'Dean’s List 2026' })).toBeHidden()
  await uts.locator('.school-more summary').click()
  await expect(education.locator('.school-logo img')).toHaveCount(3)
  for (const logo of await education.locator('.school-logo img').all()) {
    await logo.scrollIntoViewIfNeeded()
    await expect.poll(() => logo.evaluate(img => img.complete && img.naturalWidth > 0)).toBeTruthy()
  }
  await expect(education.getByText('Native', { exact: true })).toBeVisible()
  await expect(education).toContainText('Class Representative')
  await expect(education).toContainText('Class Voted Collaborator')
  await expect(education).toContainText('Dean’s List 2026')
  await expect(education.getByRole('link', { name: 'Read my student story' })).toHaveAttribute('href', /uts\.edu\.au/)
  await expect(education).toContainText('6.9 / 7.0')
  await expect(education).toContainText('9.6 / 10')
  await expect(education.getByText('IELTS', { exact: true })).toBeVisible()
  await expect(education.getByText('8.0', { exact: true })).toBeVisible()
  await expect(education.getByText('English', { exact: true })).toBeVisible()
  await expect(education.getByText('Japanese', { exact: true })).toBeVisible()
  const certificate = education.getByRole('link', { name: 'View Dean’s List certificate' })
  await expect(certificate).toBeVisible()
  expect((await page.request.get(await certificate.getAttribute('href'))).status()).toBe(200)
  await page.goto('/experience')
  await expect(page.locator('#education')).toHaveCount(0)
  await expect(page.locator('#about')).toHaveCount(0)
  await page.goto('/projects')
  await page.locator('summary').getByText('Awards & certificates', { exact: true }).click()
  await expect(page.locator('.award-item')).toHaveCount(6)
  await expect(page.locator('.awards-section')).toContainText('Accessibility Design Competition Hackathon')
  await expect(page.locator('.awards-section')).not.toContainText('Dean')
  await expect(page.locator('.evidence-card')).toHaveCount(4)
  await expect(page.locator('main')).not.toContainText('Dean')
  await expect(page.locator('main')).not.toContainText('IELTS')
  await page.goto('/projects/aquaguard')
  await page.getByText('Project certificates', { exact: true }).click()
  await expect(page.locator('.evidence-card')).toHaveCount(4)
  await expect(page.locator('main')).not.toContainText('Dean')
  await page.setViewportSize({ width: 320, height: 800 })
  await page.goto('/education')
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await expect(page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Education' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})
test('Education milestones share hover styles and keep school achievements inside accessible disclosures', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/education')
  await expect(page.locator('.education-intro h1')).toHaveCSS('font-family', /Be Vietnam Pro/)
  const cards = page.locator('.school-card')
  await expect(cards).toHaveCount(2)
  for (const card of await cards.all()) {
    await expect(card.locator('h3')).toBeVisible()
    await expect(card.locator('.education-degree')).toBeVisible()
    await expect(card.locator('.school-details')).toBeHidden()
    await card.hover()
    await expect(card).toHaveCSS('border-color', 'rgb(0, 255, 133)')
  }
  // Both school logos sit on identical plates.
  const plates = await page.locator('.school-identity .school-logo').evaluateAll(nodes => nodes.map(node => { const style = getComputedStyle(node); return [node.offsetWidth, node.offsetHeight, style.backgroundColor].join() }))
  expect(new Set(plates).size).toBe(1)
  const uts = cards.last()
  await expect(page.getByRole('heading', { name: 'Dean’s List 2026' })).toBeHidden()
  await uts.locator('.school-more summary').focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Dean’s List 2026' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Class Voted Collaborator' })).toBeVisible()
  await page.keyboard.press('Enter'); await expect(uts.locator('.school-details')).toBeHidden()
  await expect(page.locator('.education-capabilities')).toHaveCSS('position', 'sticky')
  await page.setViewportSize({ width: 320, height: 800 })
  await expect(page.locator('.education-capabilities')).toHaveCSS('position', 'static')
  await cards.first().locator('.school-more summary').click()
  await expect(cards.first().locator('.school-details')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})
