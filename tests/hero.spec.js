import { test, expect } from '@playwright/test'
test('Tom branding uses the preserved pixel asset and the focused hero keeps working', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('link', { name: 'Tom — home' })).toBeVisible()
  const wordmark = page.locator('.brand-wordmark')
  await expect(wordmark).toHaveCSS('font-size', '36px')
  await page.getByRole('link', { name: 'Tom — home' }).hover()
  await expect(wordmark.locator('span').first()).toHaveCSS('animation-name', 'none')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(wordmark.locator('span').first()).toHaveCSS('animation-name', 'brand-letter-dance')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const avatar = page.locator('.brand-avatar')
  await expect(avatar).toHaveAttribute('src', '/images/personal-images/pixel.png')
  expect(await avatar.evaluate(img => img.complete && img.naturalWidth > 0)).toBeTruthy()
  // The white backdrop is cleared: corners are transparent while the figure stays opaque.
  const alpha = await avatar.evaluate(img => { const c = document.createElement('canvas'); c.width = img.naturalWidth; c.height = img.naturalHeight; const g = c.getContext('2d'); g.drawImage(img, 0, 0)
    const at = (x, y) => g.getImageData(x, y, 1, 1).data[3]; return { corners: [at(0, 0), at(c.width - 1, 0), at(0, c.height - 1), at(c.width - 1, c.height - 1)], face: at(c.width / 2, c.height * .4) } })
  expect(alpha.corners).toEqual([0, 0, 0, 0]); expect(alpha.face).toBe(255)
  await expect(page.locator('h1')).toContainText('Tuan')
  await expect(page.locator('h1')).toContainText('Nghia')
  await expect(page.locator('link[rel="icon"]')).toHaveAttribute('href', '/images/personal-images/pixel.png?v=tom')
  await expect(page.locator('.hero-greeting')).toContainText('Hello, I’m Tuan Nghia')
  await expect(page.locator('.hero-statement')).toHaveText('AI Engineer')
  await expect(page.locator('.editorial-portrait img')).toHaveAttribute('src', '/images/optimized/portrait-cutout.webp')
  await expect(page.locator('.hero-facts > div')).toHaveCount(5)
  await expect(page.locator('.hero-facts dt')).toHaveText(['Location', 'Education', 'Research', 'Dream job', 'English'])
  await expect(page.locator('.hero-facts')).toContainText('CV & Robotics')
  await expect(page.locator('.hero-facts')).toContainText('IELTS 8.0')
  await expect(page.locator('.hero-terminal')).toHaveAttribute('aria-label', /whoami. Tuan Nghia 2007.*Engineering Intern @ IVS. AI Student @ UTS x HCMUT$/)
  await expect(page.getByRole('link', { name: 'Request Resume' })).toHaveAttribute('href', /^mailto:.*Resume/)
  await page.getByRole('link', { name: 'Explore My Work' }).click()
  await expect(page).toHaveURL(/\/projects$/)
  await expect(page).toHaveTitle(/Tuan Nghia/)
  await page.getByRole('link', { name: 'Tom — home' }).click()
  await page.getByRole('link', { name: 'Selected work', exact: true }).click()
  await expect(page).toHaveURL(/#work$/)
})
